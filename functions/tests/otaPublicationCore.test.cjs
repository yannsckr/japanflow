'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {versionKey,signer,makePublication,verifyPublication,signDelivery}=require('../otaPublicationCore.cjs');
const {canonicalPayload}=require('../otaReleaseSecurity.cjs');
const keys=crypto.generateKeyPairSync('ec',{namedCurve:'prime256v1'});
const der=keys.publicKey.export({format:'der',type:'spki'}).toString('base64');
const sign=signer(keys.privateKey.export({format:'pem',type:'pkcs8'}),der);
const draft={schemaVersion:1,bundleVersion:'48.0.1',platform:'android',title:'Test',notes:'Test',channel:'beta',status:'draft',minNativeCode:18,maxNativeCode:18,sha256:'a'.repeat(64),sizeBytes:100,storagePath:'japanflow/ota/test/00000000-0000-4000-8000-000000000001.zip'};
const make=()=>makePublication(draft,'draft','123',1,['user'],sign);
test('normalizes version aliases',()=>assert.equal(versionKey('048.00.01'),'48.0.1'));
test('rejects invalid versions',()=>assert.throws(()=>versionKey('latest')));
test('checks official key',()=>assert.throws(()=>signer(keys.privateKey.export({format:'pem',type:'pkcs8'}),'bad')));
test('signs publication without a download URL',()=>assert.equal(verifyPublication(make(),der),true));
test('rejects changed generation',()=>assert.equal(verifyPublication({...make(),generation:'124'},der),false));
test('rejects changed sequence',()=>assert.equal(verifyPublication({...make(),sequence:2},der),false));
test('rejects changed audience',()=>assert.equal(verifyPublication({...make(),targetUserIds:['other']},der),false));
test('rejects empty beta audience',()=>assert.throws(()=>makePublication(draft,'draft','123',1,[],sign)));
test('signs delivery using existing client canonical payload',()=>{const r=signDelivery(make(),'https://storage.googleapis.com/test',Date.now()+10000,sign);assert.equal(crypto.verify('sha256',Buffer.from(canonicalPayload(r)),{key:keys.publicKey,dsaEncoding:'ieee-p1363'},Buffer.from(r.signature,'base64')),true);});
